_cache: dict[str, str | None] = {}


def canon(name: str) -> str | None:
    """재료 이름 → 가격 품목. 모르면 None. 같은 이름은 한 번만 계산한다(ingredient 표 11만 이름)."""
    if name in _cache:
        return _cache[name]
    s = _normalize(name)
    result: str | None = None
    if s in _LOOKUP:
        result = _LOOKUP[s]
    else:
        # 손질 말을 떼고 다시: '다진 청양고추' → '청양고추', '얇게 썬 양파' → '양파'
        stripped = _MODIFIER.sub("", s)
        while stripped != s and stripped not in _LOOKUP and _MODIFIER.sub("", stripped) != stripped:
            stripped = _MODIFIER.sub("", stripped)
        if stripped in _LOOKUP:
            result = _LOOKUP[stripped]
        else:
            # 끝이 품목명으로 끝나는 이름: '손질 오징어' → 오징어, '통 삼겹살' → 삼겹살. 두 글자 이상만(‘무’ 같은 한 글자는 오인이 많다).
            for key in sorted(_LOOKUP, key=len, reverse=True):
                if len(key) >= 2 and stripped.endswith(key) and _LOOKUP[key] is not None:
                    result = _LOOKUP[key]
                    break
    _cache[name] = result
    return result


