def _normalize(name: str) -> str:
    s = _PAREN.sub("", name.strip())
    s = _SPACE.sub("", s).lower()
    s = _TAIL.sub("", s)
    if len(s) > 2:
        s = _TRAIL_QTY.sub("", s) or s
    return s


