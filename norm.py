PIECE_DEFAULT = 100
# '약간·조금·적당량·취향껏' - 양념이면 2g, 주재료면 30g. 품목이 양념인지의 기준은 PIECE_G 30g 이하 + 조미료.
SEASONING = {"소금", "설탕", "식초", "간장", "고추장", "된장", "고춧가루", "참기름", "식용유", "마요네즈", "케찹", "마늘", "생강", "쪽파", "고추", "풋고추", "마른멸치", "맛김", "미역", "다시마"}
_VAGUE = re.compile(r"(약간|조금|적당량|적당히|취향껏|기호|적당|살짝|톡톡|솔솔|한꼬집|두꼬집|꼬집)")
_NUM = re.compile(r"(\d+(?:[.,]\d+)?)?\s*(?:(\d+)\s*/\s*(\d+))?")
_KOR_NUM = {"한": 1, "두": 2, "세": 3, "네": 4, "다섯": 5, "여섯": 6, "일곱": 7, "여덟": 8, "아홉": 9, "열": 10, "반": 0.5}
_RANGE = re.compile(r"(\d+(?:[.,]\d+)?)\s*[~\-–]\s*(\d+(?:[.,]\d+)?)")


def _number(text: str) -> tuple[float | None, str]:
    """앞머리의 수(정수·소수·분수·대분수·범위·한두세·반)를 떼어 (값, 나머지)."""
    s = text.strip().replace("½", "1/2").replace("¼", "1/4").replace("¾", "3/4").replace("⅓", "1/3").replace("⅔", "2/3")
    m = _RANGE.match(s)
    if m:
        return (float(m.group(1).replace(",", ".")) + float(m.group(2).replace(",", "."))) / 2, s[m.end():]
    m = re.match(r"(?:(\d+)\s+)?(\d+)\s*/\s*(\d+)", s)  # 분수·대분수: 1/2, 1 1/2
    if m and float(m.group(3)):
        value, rest = float(m.group(1) or 0) + float(m.group(2)) / float(m.group(3)), s[m.end():]
    else:
        m = re.match(r"(\d+(?:[.,]\d+)?)", s)
        value, rest = (float(m.group(1).replace(",", ".")), s[m.end():]) if m else (None, s)
    if value is not None:
        # '1개반', '1컵반' → +0.5
        if rest.endswith("반"):
            value += 0.5
            rest = rest[:-1]
        return value, rest
    for k, v in _KOR_NUM.items():
        if s.startswith(k):
            return float(v), s[len(k):]
    return None, s


def grams(item: str | None, qty: str) -> float | None:
    """재료 양 문자열 → g. 모르면 None(원가 계산에서 그 재료는 품목 기본 1개분으로 본다 - cost.py)."""
    q = (qty or "").strip()  # T/t 구분 때문에 소문자로 바꾸지 않는다
    if not q:
        return None
    if _VAGUE.search(q):
        return 2.0 if item in SEASONING else 30.0
    value, rest = _number(q)
    unit = re.sub(r"[\s()\[\]]", "", rest)
    unit = re.sub(r"(정도|쯤|가량|이상|이하|넉넉히|듬뿍|수북이|가득|분량|씩)$", "", unit)
    if value is None:
        return None
    if unit == "" :
        # 수만 있으면 '개'로 본다
        return value * PIECE_G.get(item or "", PIECE_DEFAULT)
    for name in sorted(UNIT_G, key=len, reverse=True):
        if unit.startswith(name):
            g = UNIT_G[name]
            if g is None:
                return value * PIECE_G.get(item or "", PIECE_DEFAULT)
            return value * g
    return None


