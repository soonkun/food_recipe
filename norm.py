for _item, _names in ALIASES.items():
    for _n in _names + [_item]:
        _LOOKUP.setdefault(_normalize(_n), _item)
for _group, _names in UNPRICED.items():
    for _n in _names:
        _LOOKUP.setdefault(_normalize(_n), None)
